#!/bin/bash
#
# Unit tests for the on-disk config migrations in scripts/lib/migrate.sh.
#
set -uo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$DIR/test-helpers.sh"
source "$DIR/../scripts/lib/migrate.sh"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# --- arm_migrate_media_paths: upstream defaults are rewritten -----------------
cat > "$TMP/arm.yaml" <<'EOF'
# Path to raw MakeMKV directory
RAW_PATH: "/home/arm/media/raw/"
TRANSCODE_PATH: "/home/arm/media/transcode/"
COMPLETED_PATH: "/home/arm/media/completed/"
LOGPATH: "/home/arm/logs/"
EOF

out=$(arm_migrate_media_paths "$TMP/arm.yaml"); rc=$?
assert_rc 0 "$rc" "migrate defaults: rc 0"
assert_eq 'RAW_PATH: "/home/arm/movies/arm/raw/"' "$(grep '^RAW_PATH:' "$TMP/arm.yaml")" "RAW_PATH moved under /home/arm/movies/arm"
assert_eq 'TRANSCODE_PATH: "/home/arm/movies/arm/transcode/"' "$(grep '^TRANSCODE_PATH:' "$TMP/arm.yaml")" "TRANSCODE_PATH moved under /home/arm/movies/arm"
assert_eq 'COMPLETED_PATH: "/home/arm/movies/"' "$(grep '^COMPLETED_PATH:' "$TMP/arm.yaml")" "COMPLETED_PATH points at library root"
assert_eq 'LOGPATH: "/home/arm/logs/"' "$(grep '^LOGPATH:' "$TMP/arm.yaml")" "unrelated keys untouched"
assert_eq "# Path to raw MakeMKV directory" "$(head -1 "$TMP/arm.yaml")" "comments untouched"
assert_eq $'RAW_PATH\nTRANSCODE_PATH\nCOMPLETED_PATH' "$out" "reports each migrated key"

# --- idempotent: a second run changes nothing and reports nothing -------------
before=$(cat "$TMP/arm.yaml")
out=$(arm_migrate_media_paths "$TMP/arm.yaml"); rc=$?
assert_rc 0 "$rc" "re-run: rc 0"
assert_eq "" "$out" "re-run reports nothing"
assert_eq "$before" "$(cat "$TMP/arm.yaml")" "re-run leaves file unchanged"

# --- user-customised paths are left alone ------------------------------------
cat > "$TMP/custom.yaml" <<'EOF'
RAW_PATH: "/home/arm/movies/scratch/raw/"
TRANSCODE_PATH: "/home/arm/media/transcode/"
COMPLETED_PATH: "/home/arm/movies/rips/"
EOF
out=$(arm_migrate_media_paths "$TMP/custom.yaml")
assert_eq 'RAW_PATH: "/home/arm/movies/scratch/raw/"' "$(grep '^RAW_PATH:' "$TMP/custom.yaml")" "custom RAW_PATH preserved"
assert_eq 'COMPLETED_PATH: "/home/arm/movies/rips/"' "$(grep '^COMPLETED_PATH:' "$TMP/custom.yaml")" "custom COMPLETED_PATH preserved"
assert_eq 'TRANSCODE_PATH: "/home/arm/movies/arm/transcode/"' "$(grep '^TRANSCODE_PATH:' "$TMP/custom.yaml")" "default TRANSCODE_PATH still migrated"
assert_eq "TRANSCODE_PATH" "$out" "reports only the key it changed"

# --- missing file is an error, not a silent no-op ----------------------------
arm_migrate_media_paths "$TMP/does-not-exist.yaml" >/dev/null 2>&1; rc=$?
assert_rc 1 "$rc" "missing file: rc 1"

# --- homepage_migrate_services: Jellyfin 12 / Tdarr 3 widget fields -----------
# Shape of a services.yaml generated by older installs (no blank lines between).
cat > "$TMP/services.yaml" <<'EOF'
---
- Media Streaming:
    - Jellyfin:
        icon: jellyfin.svg
        widget:
          type: jellyfin
          url: http://192.168.8.200:8096
          key: {{HOMEPAGE_VAR_JELLYFIN_API_KEY}}
          enableBlocks: true
    - Jellyseerr:
        widget:
          type: jellyseerr
          url: http://192.168.8.200:5055
- Media Production:
    - Tdarr:
        widget:
          type: tdarr
          url: http://192.168.8.200:8265
    - ARM:
        icon: sh-automatic-ripping-machine
EOF
out=$(homepage_migrate_services "$TMP/services.yaml"); rc=$?
assert_rc 0 "$rc" "homepage: rc 0"
assert_eq $'jellyfin.version\ntdarr.key' "$out" "homepage: reports both changes"
assert_eq "          version: 2" "$(sed -n '/type: jellyfin$/,/^    - /p' "$TMP/services.yaml" | grep 'version:')" "jellyfin widget gets version: 2 at widget indent"
assert_eq "          key: {{HOMEPAGE_VAR_TDARR_API_KEY}}" "$(sed -n '/type: tdarr$/,/^    - /p' "$TMP/services.yaml" | grep 'key:')" "tdarr widget gets key at widget indent"
assert_eq "1" "$(grep -c 'version:' "$TMP/services.yaml")" "seerr/jellyseerr widget not given a version"
assert_eq "    - ARM:" "$(grep -A1 'HOMEPAGE_VAR_TDARR_API_KEY' "$TMP/services.yaml" | tail -1)" "insertion lands before the next service"
before=$(cat "$TMP/services.yaml")
out=$(homepage_migrate_services "$TMP/services.yaml")
assert_eq "" "$out" "homepage: re-run reports nothing"
assert_eq "$before" "$(cat "$TMP/services.yaml")" "homepage: re-run leaves file unchanged"

# Widget block ending at EOF, and existing fields respected.
printf '        widget:\n          type: tdarr\n          key: custom\n' > "$TMP/eof.yaml"
printf '        widget:\n          type: jellyfin\n          url: x\n' >> "$TMP/eof.yaml"
out=$(homepage_migrate_services "$TMP/eof.yaml")
assert_eq "jellyfin.version" "$out" "existing tdarr key kept; jellyfin at EOF migrated"
assert_eq "          version: 2" "$(tail -1 "$TMP/eof.yaml")" "insertion at EOF"
assert_eq "1" "$(grep -c 'key:' "$TMP/eof.yaml")" "no duplicate tdarr key"

homepage_migrate_services "$TMP/does-not-exist.yaml" >/dev/null 2>&1; rc=$?
assert_rc 1 "$rc" "homepage: missing file rc 1"

# --- recyclarr_migrate_config: v8 key removal + corrected TRaSH IDs ----------
cat > "$TMP/recyclarr.yml" <<'EOF'
sonarr:
  tv-shows:
    delete_old_custom_formats: true
    replace_existing_custom_formats: true
    custom_formats:
      - trash_ids:
          - d6819cba26b1a6508138d25fb5e32293  # AMZN (Amazon)
          - 77a7b25585c18af08f60b1547bb9b4fb  # ATVP (Apple TV+)
          - a880d6abc21e7c16884f3ae393f84179  # HULU
          - 3ac5d84fce98bab1b531393e9c82f467  # iT (iTunes)
          - d6819cba26b1a6508138d25fb5e32293  # HD Bluray Tier 01 (user's own)
radarr:
  movies:
    replace_existing_custom_formats: true
    custom_formats:
      - trash_ids:
          - 0f12c086e289cf966fa5948eac571f44  # Theatrical Cut
EOF
out=$(recyclarr_migrate_config "$TMP/recyclarr.yml"); rc=$?
assert_rc 0 "$rc" "recyclarr: rc 0"
assert_eq "0" "$(grep -c 'replace_existing_custom_formats' "$TMP/recyclarr.yml")" "removed v8-deleted key"
assert_eq "          - d660701077794679fd59e8bdf4ce3a29  # AMZN (Amazon)" "$(grep '# AMZN' "$TMP/recyclarr.yml")" "AMZN id corrected"
assert_eq "          - f67c9ca88f463a48346062e8ad07713f  # ATVP (Apple TV+)" "$(grep '# ATVP' "$TMP/recyclarr.yml")" "ATVP id corrected"
assert_eq "          - f6cce30f1733d5c8194222a7507909bb  # HULU" "$(grep '# HULU' "$TMP/recyclarr.yml")" "HULU id corrected"
assert_eq "          - 0ac24a2a68a9700bcb7eeca8e5cd644c  # iT (iTunes)" "$(grep '# iT ' "$TMP/recyclarr.yml")" "iT id corrected"
assert_eq "          - e9001909a4c88013a359d0b9920d7bea  # Theatrical Cut" "$(grep '# Theatrical' "$TMP/recyclarr.yml")" "Theatrical Cut id corrected"
assert_eq "          - d6819cba26b1a6508138d25fb5e32293  # HD Bluray Tier 01 (user's own)" "$(grep 'Tier 01' "$TMP/recyclarr.yml")" "same id with a different comment left alone"
assert_eq "6" "$(printf '%s\n' "$out" | grep -c .)" "recyclarr: reports key removal + 5 id fixes"
before=$(cat "$TMP/recyclarr.yml")
out=$(recyclarr_migrate_config "$TMP/recyclarr.yml")
assert_eq "" "$out" "recyclarr: re-run reports nothing"
assert_eq "$before" "$(cat "$TMP/recyclarr.yml")" "recyclarr: re-run leaves file unchanged"

# The shipped template must already be clean (nothing for the migration to do).
cp "$DIR/../config/recyclarr.yml" "$TMP/template.yml"
assert_eq "" "$(recyclarr_migrate_config "$TMP/template.yml")" "config/recyclarr.yml template needs no migration"

# --- Seerr runs as a fixed UID regardless of PUID ----------------------------
assert_eq "1000" "$SEERR_UID" "SEERR_UID is the image's node user"
assert_eq "1000" "$SEERR_GID" "SEERR_GID is the image's node group"

finish_tests
